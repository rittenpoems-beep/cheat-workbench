import asyncio
import importlib.util
import json
import os
import re
import shutil
import sys
import time
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Callable
from urllib.parse import quote, urlparse

CREATOR_HOME = "https://creator.douyin.com/creator-micro/home"
CREATOR_CONTENT = "https://creator.douyin.com/creator-micro/content/manage"
PUBLIC_HOT = "https://www.douyin.com/hot"
WORK_ENDPOINTS = (
    "/janus/douyin/creator/pc/work_list",
    "/aweme/v1/creator/item/list",
)
ACCOUNT_ENDPOINTS = ("/user/info", "/user_info", "/account/info", "/account/get")
MARKER = ".workbench-collector-session.json"
ARRAY_KEYS = ("aweme_list", "item_list", "items", "list", "work_list")
METRIC_KEYS = {
    "plays": ("play_count", "play_cnt"),
    "likes": ("digg_count", "like_count", "digg_cnt"),
    "comments": ("comment_count", "comment_cnt"),
    "shares": ("share_count", "share_cnt"),
    "collects": ("collect_count", "collect_cnt", "favorite_count"),
}


class CollectorError(Exception):
    def __init__(self, code: str, message: str) -> None:
        super().__init__(message)
        self.code = code


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")


def emit(kind: str, message: str, **fields: Any) -> None:
    print(json.dumps({"type": kind, "message": message, "at": utc_now(), **fields}, ensure_ascii=False), flush=True)


def atomic_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(path.name + ".tmp")
    temp.write_text(json.dumps(value, ensure_ascii=False, indent=2), encoding="utf-8")
    os.replace(temp, path)


def numeric(value: Any) -> int | float | None:
    """Preserve genuine zero; do not turn missing or approximate counts into zero."""
    if isinstance(value, bool) or value is None:
        return None
    if isinstance(value, (int, float)):
        return value if value >= 0 and value != float("inf") and value == value else None
    if isinstance(value, str) and re.fullmatch(r"\d+(?:\.\d+)?", value.strip()):
        return float(value) if "." in value else int(value)
    return None


def timestamp(value: Any) -> str:
    if isinstance(value, str) and not value.isdigit():
        try:
            parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
            if parsed.tzinfo is None:
                return ""  # Do not guess a platform-local timezone.
            return parsed.astimezone(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")
        except ValueError:
            return ""
    number = numeric(value)
    if number is None or number <= 0:
        return ""
    try:
        if number > 10**12:
            number /= 1000
        return datetime.fromtimestamp(number, timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")
    except (ValueError, OverflowError, OSError):
        return ""


def video_candidates(payload: Any) -> list[dict[str, Any]]:
    """Adapter's list shapes, extended for nested data and item wrappers."""
    if not isinstance(payload, dict):
        return []
    node = payload
    for _ in range(4):
        for key in ARRAY_KEYS:
            if isinstance(node.get(key), list):
                return [item for item in node[key] if isinstance(item, dict)]
        if not isinstance(node.get("data"), dict):
            return []
        node = node["data"]
    return []


def unwrap_video(value: dict[str, Any]) -> dict[str, Any]:
    for key in ("aweme_info", "item_info", "aweme", "item"):
        if isinstance(value.get(key), dict):
            return {**value, **value[key]}
    return value


def normalize_work(value: dict[str, Any], captured_at: str, upstream: Callable | None = None) -> dict[str, Any] | None:
    raw = unwrap_video(value)
    # Reuse upstream metadata normalization; retain raw metrics because upstream
    # historically uses zero as the fallback for an unavailable count.
    metadata = upstream(raw) if upstream else {
        "aweme_id": raw.get("aweme_id") or raw.get("item_id") or raw.get("id"),
        "desc": raw.get("desc") or raw.get("title") or "",
        "create_time": raw.get("create_time") or raw.get("createTime"),
    }
    work_id = str(metadata.get("aweme_id") or "")
    if not re.fullmatch(r"\d+", work_id):
        return None
    metrics: dict[str, int | float | None] = {}
    containers = [raw.get("statistics"), raw.get("stats"), raw.get("statistic_data"), raw]
    for field, aliases in METRIC_KEYS.items():
        metrics[field] = None
        for container in containers:
            if not isinstance(container, dict):
                continue
            for alias in aliases:
                count = numeric(container.get(alias))
                if count is not None:
                    metrics[field] = count
                    break
            if metrics[field] is not None:
                break
    desc = str(metadata.get("desc") or "")
    return {
        "id": work_id,
        "title": desc or "（未提供标题）",
        "description": desc,
        "url": f"https://www.douyin.com/video/{work_id}",
        "publishedAt": timestamp(metadata.get("create_time")),
        "capturedAt": captured_at,
        "metrics": metrics,
        "source": "douyin-session",
    }


def merge_works(existing: list[dict], incoming: list[dict], limit: int) -> list[dict]:
    """A later response can fill a missing field without erasing valid counts."""
    by_id = {item["id"]: item for item in existing}
    for item in incoming:
        if item["id"] not in by_id:
            by_id[item["id"]] = item
            continue
        old = by_id[item["id"]]
        by_id[item["id"]] = {
            **old,
            **{key: val for key, val in item.items() if val not in (None, "") and key != "metrics"},
            "metrics": {key: item["metrics"].get(key) if item["metrics"].get(key) is not None else old["metrics"].get(key) for key in METRIC_KEYS},
        }
    return list(by_id.values())[:limit]


def account_from_payload(payload: Any) -> dict[str, str] | None:
    if not isinstance(payload, dict):
        return None
    candidates = [payload]
    for _ in range(3):
        next_candidates: list[dict] = []
        for node in candidates:
            name = node.get("nickname") or node.get("user_name") or node.get("nick_name")
            if isinstance(name, str) and name.strip():
                account = {"name": name.strip()}
                account_id = node.get("unique_id") or node.get("unique_uid") or node.get("short_id") or node.get("uid")
                if isinstance(account_id, (str, int)):
                    account["id"] = str(account_id)
                return account
            for key in ("data", "user", "user_info", "author", "account"):
                if isinstance(node.get(key), dict):
                    next_candidates.append(node[key])
        candidates = next_candidates
    return None


def normalize_trends(payload: Any, captured_at: str, limit: int = 20) -> list[dict]:
    node = payload.get("data", payload) if isinstance(payload, dict) else {}
    entries = node.get("word_list") or node.get("list") or [] if isinstance(node, dict) else []
    topics: list[dict] = []
    seen: set[str] = set()
    for index, item in enumerate(entries if isinstance(entries, list) else []):
        if not isinstance(item, dict):
            continue
        word = item.get("word") or item.get("sentence") or item.get("title")
        if not isinstance(word, str) or not word.strip() or word in seen:
            continue
        seen.add(word)
        position = numeric(item.get("position"))
        topics.append({
            "title": word,
            "url": "https://www.douyin.com/search/" + quote(word, safe=""),
            "rank": position if position is not None else index + 1,
            "heat": numeric(item.get("hot_value")),
            "capturedAt": captured_at,
            "source": "douyin-hot",
        })
    return topics[:limit]


def safe_absolute(value: str, label: str) -> Path:
    given = Path(value).expanduser()
    if not given.is_absolute():
        raise CollectorError("UNSAFE_PATH", f"{label} 必须为绝对路径")
    return given.resolve()


class SessionDirectory:
    """Only delete a profile created in an empty, explicitly named task directory."""
    def __init__(self, path: Path) -> None:
        self.path = path
        self.profile = path / "profile"
        self.token = str(uuid.uuid4())

    def create(self) -> None:
        if self.path == Path(self.path.anchor) or len(self.path.parts) < 3 or self.path == Path.home().resolve():
            raise CollectorError("UNSAFE_PATH", "拒绝在根目录或用户主目录创建临时会话")
        if self.path.exists() and any(self.path.iterdir()):
            raise CollectorError("SESSION_NOT_EMPTY", "临时会话目录不是空目录；不会读取或删除已有登录资料")
        self.path.mkdir(parents=True, exist_ok=True)
        atomic_json(self.path / MARKER, {"token": self.token, "pid": os.getpid(), "createdAt": utc_now()})
        self.profile.mkdir()

    def cleanup(self) -> bool:
        marker = self.path / MARKER
        if not marker.exists():
            if self.profile.exists() or self.profile.is_symlink():
                raise CollectorError("UNSAFE_CLEANUP", "临时目录标记缺失但浏览器资料仍存在，不能确认清理")
            return True
        try:
            stored = json.loads(marker.read_text(encoding="utf-8"))
        except (ValueError, OSError) as exc:
            raise CollectorError("UNSAFE_CLEANUP", "临时目录标记无法验证，拒绝清理未知目录") from exc
        if not isinstance(stored, dict):
            raise CollectorError("UNSAFE_CLEANUP", "临时目录标记格式无效，拒绝清理未知目录")
        if stored.get("token") != self.token:
            raise CollectorError("UNSAFE_CLEANUP", "临时目录标记改变，拒绝清理不属于本进程的目录")
        if self.profile.is_symlink() or (hasattr(self.profile, "is_junction") and self.profile.is_junction()):
            raise CollectorError("UNSAFE_CLEANUP", "临时浏览器目录被替换为链接，拒绝递归删除")
        if self.profile.exists():
            expected = self.path.resolve() / "profile"
            if self.profile.resolve() != expected:
                raise CollectorError("UNSAFE_CLEANUP", "临时目录已改变，拒绝清理")
            shutil.rmtree(self.profile)
        if self.profile.exists() or self.profile.is_symlink():
            raise CollectorError("CLEANUP_FAILED", "临时浏览器资料删除后仍存在，不能确认清理")
        atomic_json(marker, {**stored, "cleanedAt": utc_now(), "profileRemoved": True})
        return True


def load_upstream_normalizer() -> Callable:
    upstream_dir = Path(__file__).resolve().parents[3] / "adapters" / "perf-data" / "douyin-session"
    spec = importlib.util.spec_from_file_location("workbench_upstream_douyin_crawler", upstream_dir / "crawler.py")
    if spec is None or spec.loader is None:
        raise CollectorError("UPSTREAM_MISSING", "上游 douyin-session adapter 不存在")
    module = importlib.util.module_from_spec(spec)
    sys.path.insert(0, str(upstream_dir))
    try:
        spec.loader.exec_module(module)
    finally:
        sys.path.remove(str(upstream_dir))
    return module._normalize_video


def check_cancel(path: Path | None) -> None:
    if path and path.exists():
        raise CollectorError("CANCELLED", "用户取消了同步，正在清理临时登录资料")


async def pause(seconds: float, cancel: Path | None) -> None:
    end = time.monotonic() + seconds
    while time.monotonic() < end:
        check_cancel(cancel)
        await asyncio.sleep(min(0.25, max(0, end - time.monotonic())))


async def logged_in(context: Any, page: Any) -> bool:
    # Cookie values never leave this process and are never written separately.
    cookies = await context.cookies("https://creator.douyin.com")
    has_session = any(cookie.get("name") in ("sessionid", "sessionid_ss") for cookie in cookies)
    return has_session and "login" not in urlparse(page.url).path


async def login_view(context: Any, page: Any, path: Path) -> bool:
    if await logged_in(context, page):
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(path.stem + ".pending.png")
    # Entire login viewport is intentional: it includes QR expiry and platform
    # verification prompts. No authenticated page is captured.
    await page.screenshot(path=str(temp), type="png", timeout=5000)
    if await logged_in(context, page):
        temp.unlink(missing_ok=True)
        return False
    os.replace(temp, path)
    return True


async def visible_account(page: Any) -> dict[str, str] | None:
    for selector in ('[class*="header"] [class*="nickname"]', '[class*="user-info"] [class*="name"]', '[class*="userInfo"] [class*="name"]'):
        locator = page.locator(selector).first
        try:
            if await locator.is_visible(timeout=500):
                text = (await locator.inner_text(timeout=500)).strip()
                if text and len(text) < 100:
                    return {"name": text}
        except Exception:
            pass
    return None


class ResponseState:
    def __init__(self, limit: int, upstream: Callable) -> None:
        self.limit, self.upstream = limit, upstream
        self.works: list[dict] = []
        self.account: dict[str, str] | None = None
        self.errors: list[str] = []
        self.responses = 0
        self.more: bool | None = None

    async def observe(self, response: Any) -> None:
        parsed = urlparse(response.url)
        if parsed.hostname != "creator.douyin.com":
            return
        is_work = any(endpoint in parsed.path for endpoint in WORK_ENDPOINTS)
        is_account = any(endpoint in parsed.path for endpoint in ACCOUNT_ENDPOINTS)
        if not is_work and not is_account:
            return
        if not 200 <= response.status < 300:
            if is_work:
                self.errors.append(f"作品接口 HTTP {response.status}")
            return
        try:
            payload = await response.json()
        except Exception:
            if is_work:
                self.errors.append("作品接口没有返回有效 JSON（可能是空响应或验证页面）")
            return
        if not isinstance(payload, dict):
            return
        status = payload.get("status_code", payload.get("status", 0))
        if status not in (0, "0", "success", None):
            if is_work:
                self.errors.append(f"作品接口返回非成功状态 {str(status)[:30]}")
            return
        if is_account:
            self.account = account_from_payload(payload) or self.account
        if not is_work:
            return
        self.responses += 1
        items = video_candidates(payload)
        normalized = [normalize_work(item, utc_now(), self.upstream) for item in items]
        self.works = merge_works(self.works, [item for item in normalized if item], self.limit)
        if not self.account and items:
            # Creator work list belongs to the authenticated account. Use only
            # explicit author/user_info structures, never a title or guessed ID.
            raw = unwrap_video(items[0])
            for key in ("author", "user_info"):
                self.account = account_from_payload(raw.get(key)) or self.account
        for node in (payload, payload.get("data")):
            if isinstance(node, dict):
                for key in ("has_more", "hasMore"):
                    if node.get(key) in (True, 1, "1"):
                        self.more = True
                    elif node.get(key) in (False, 0, "0"):
                        self.more = False


async def paginate(page: Any) -> None:
    # Use the same controls a person can use. Do not manufacture signed calls.
    selectors = (
        'button[aria-label*="下一页"]', '[title="下一页"]',
        '.ant-pagination-next:not(.ant-pagination-disabled) button',
        '[class*="pagination-next"]:not([aria-disabled="true"])',
    )
    for selector in selectors:
        control = page.locator(selector).first
        try:
            if await control.is_visible(timeout=500) and await control.is_enabled(timeout=500):
                await control.click(timeout=1500)
                return
        except Exception:
            continue
    control = page.get_by_role("button", name=re.compile(r"下一页|下一步"))
    if await control.count() == 1:
        try:
            if await control.is_enabled(timeout=500):
                await control.click(timeout=1500)
                return
        except Exception:
            pass
    await page.evaluate("""() => {
      const candidates = [...document.querySelectorAll('main, [class*="content"], [class*="list"], [class*="scroll"]')];
      const scrollable = candidates.filter(el => el.scrollHeight > el.clientHeight + 100 && el.clientHeight > 100);
      for (const el of scrollable) el.scrollTop = el.scrollHeight;
      window.scrollBy(0, 1400);
    }""")


async def run_sync(args: argparse.Namespace) -> dict:
    from playwright.async_api import async_playwright

    upstream = load_upstream_normalizer()
    session = SessionDirectory(safe_absolute(args.session_dir, "session-dir"))
    output, view = safe_absolute(args.output, "output"), safe_absolute(args.view, "view")
    confirm = safe_absolute(args.confirm, "confirm") if args.confirm else session.path / "confirm.json"
    cancel = safe_absolute(args.cancel, "cancel") if args.cancel else session.path / "cancel"
    if output == view or session.profile in output.parents or session.profile in view.parents:
        raise CollectorError("UNSAFE_PATH", "结果和截图不得保存在临时浏览器资料目录内")
    if confirm.exists() or cancel.exists():
        raise CollectorError("STALE_CONTROL_FILE", "确认或取消文件已经存在，请为新任务使用独立目录")
    session.create()
    context, pw = None, None
    response_tasks: set[asyncio.Task] = set()
    state = ResponseState(args.limit, upstream)
    result: dict | None = None
    try:
        emit("progress", "启动独立临时浏览器；不会读取已有浏览器登录", phase="launch")
        pw = await async_playwright().start()
        context = await pw.chromium.launch_persistent_context(
            str(session.profile), headless=not args.visible,
            viewport={"width": 1100, "height": 800}, locale="zh-CN",
        )
        page = context.pages[0] if context.pages else await context.new_page()

        def observe(response: Any) -> None:
            task = asyncio.create_task(state.observe(response))
            response_tasks.add(task)
            task.add_done_callback(response_tasks.discard)

        page.on("response", observe)
        await page.goto(CREATOR_HOME, wait_until="domcontentloaded", timeout=45000)
        emit("progress", "请用手机扫码登录你自己的抖音账号；额外验证须由本人正常完成", phase="login", viewReady=False)
        deadline, last_screenshot = time.monotonic() + args.login_timeout, 0.0
        last_view_ready: bool | None = None
        while time.monotonic() < deadline:
            check_cancel(cancel)
            if await logged_in(context, page):
                break
            if time.monotonic() - last_screenshot >= 1.5:
                try:
                    ready = await login_view(context, page, view)
                    if ready != last_view_ready:
                        emit("progress", "等待扫码登录，请用抖音扫描当前登录画面" if ready else "等待抖音登录页面加载", phase="login", viewReady=ready)
                        last_view_ready = ready
                except Exception:
                    if last_view_ready is not False:
                        emit("progress", "等待抖音登录页面加载", phase="login", viewReady=view.exists())
                        last_view_ready = False
                last_screenshot = time.monotonic()
            await pause(0.4, cancel)
        else:
            raise CollectorError("LOGIN_TIMEOUT", "扫码登录超时；未采集作品，请重新连接")

        view.unlink(missing_ok=True)
        await pause(1, cancel)
        state.account = state.account or await visible_account(page)
        account = state.account or {"name": ""}
        emit("account", "已登录，请确认这是本次要同步的账号" if state.account else "已登录，但未取得账号名；请确认本次扫码账号后继续", account=account, identityKnown=bool(state.account), confirmPath=str(confirm), phase="confirm")
        confirm_deadline = time.monotonic() + args.confirm_timeout
        while time.monotonic() < confirm_deadline:
            check_cancel(cancel)
            if confirm.exists():
                try:
                    approved = json.loads(confirm.read_text(encoding="utf-8")).get("confirmed") is True
                except (OSError, ValueError, AttributeError):
                    approved = False
                if approved:
                    break
            await pause(0.4, cancel)
        else:
            raise CollectorError("CONFIRM_TIMEOUT", "账号确认超时，已取消同步")

        # Throw away any homepage work response until the owner has confirmed.
        state.works = []
        state.responses = 0
        state.more = None
        state.errors = []
        emit("progress", "账号已确认，正在打开创作者作品管理页", phase="collect", count=0)
        await page.goto(CREATOR_CONTENT, wait_until="domcontentloaded", timeout=45000)
        await pause(7, cancel)
        stagnant, previous = 0, 0
        for _ in range(args.max_pages):
            count = len(state.works)
            emit("progress", f"已读取 {count} 条真实作品", phase="collect", count=count, requested=args.limit)
            if count >= args.limit or (state.responses and state.more is False):
                break
            stagnant = stagnant + 1 if count == previous else 0
            previous = count
            if stagnant >= 4:
                break
            await paginate(page)
            await pause(2, cancel)
        if response_tasks:
            await asyncio.gather(*list(response_tasks), return_exceptions=True)
        if not state.works:
            detail = state.errors[-1] if state.errors else "页面未返回可识别的作品列表 JSON；账号可能没有作品、正在验证，或平台接口已经改变"
            raise CollectorError("NO_WORKS", "登录成功，但没有取得真实作品：" + detail)
        valid_metrics = sum(any(value is not None for value in work["metrics"].values()) for work in state.works)
        if valid_metrics == 0:
            raise CollectorError("NO_METRICS", f"取得 {len(state.works)} 条作品元数据，但没有任何可验证指标；未把本次同步标记为成功")
        result = {
            "account": state.account or account,
            "works": state.works,
            "capturedAt": utc_now(),
            "requested": args.limit,
            "metricsAvailable": valid_metrics,
            "warnings": state.errors[-3:] + ([f"只取得 {len(state.works)} / {args.limit} 条；可能少于目标数量或翻页未继续"] if len(state.works) < args.limit else []),
        }
    finally:
        browser_closed = context is None
        if context:
            try:
                await asyncio.wait_for(context.close(), timeout=10)
                browser_closed = True
            except Exception:
                pass
        if pw:
            try:
                await asyncio.wait_for(pw.stop(), timeout=5)
            except Exception:
                # Driver shutdown must not prevent deletion of the profile.
                pass
        if context and not browser_closed:
            try:
                browser_closed = context.browser is not None and not context.browser.is_connected()
            except Exception:
                browser_closed = False
        for task in list(response_tasks):
            task.cancel()
        cleanup_error: Exception | None = None
        for attempt in range(5):
            try:
                session.cleanup()
                cleanup_error = None
                break
            except (OSError, CollectorError) as exc:
                cleanup_error = exc
                await asyncio.sleep(0.25 * (attempt + 1))
        artifacts = [view, view.with_name(view.stem + ".pending.png"), confirm]
        for artifact in artifacts:
            artifact_error: Exception | None = None
            for attempt in range(5):
                try:
                    artifact.unlink(missing_ok=True)
                    artifact_error = None
                    break
                except OSError as exc:
                    artifact_error = exc
                    await asyncio.sleep(0.15 * (attempt + 1))
            cleanup_error = cleanup_error or artifact_error
        profile_removed = not (session.profile.exists() or session.profile.is_symlink())
        artifacts_removed = all(not (artifact.exists() or artifact.is_symlink()) for artifact in artifacts)
        if cleanup_error or not profile_removed or not artifacts_removed or not browser_closed:
            emit("error", "临时登录资料或浏览器关闭状态未通过清理验证，请检查该任务", code="CLEANUP_FAILED", profileRemoved=profile_removed, loginViewRemoved=artifacts_removed, browserClosed=browser_closed)
            raise CollectorError("CLEANUP_FAILED", "临时会话清理尚未完全验证，不能报告完成") from cleanup_error
        emit("progress", "临时浏览器已关闭，登录资料和二维码截图已删除", phase="cleanup", profileRemoved=True, loginViewRemoved=True, browserClosed=True)
    assert result is not None
    result["cleanup"] = {"profileRemoved": True, "loginViewRemoved": True, "browserClosed": True}
    atomic_json(output, result)
    emit("complete", f"同步完成：{len(result['works'])} 条真实作品", account=result["account"], count=len(result["works"]), output=str(output), profileRemoved=True)
    return result


async def run_trends(args: argparse.Namespace) -> dict:
    from playwright.async_api import async_playwright

    output = safe_absolute(args.output, "output")
    cancel = safe_absolute(args.cancel, "cancel") if args.cancel else None
    topics: list[dict] = []
    failures: list[str] = []
    pending: set[asyncio.Task] = set()

    async def observe(response: Any) -> None:
        nonlocal topics
        parsed = urlparse(response.url)
        if parsed.hostname not in ("www.douyin.com", "douyin.com") or "/hot/search/list" not in parsed.path:
            return
        if not 200 <= response.status < 300:
            failures.append(f"热榜接口 HTTP {response.status}")
            return
        try:
            payload = await response.json()
            if payload.get("status_code", 0) not in (0, "0", None):
                failures.append("热榜接口返回非成功状态")
                return
            topics = normalize_trends(payload, utc_now(), args.limit) or topics
        except Exception:
            failures.append("热榜接口返回空内容或无效 JSON")

    async with async_playwright() as pw:
        browser = await pw.chromium.launch(headless=True)
        try:
            context = await browser.new_context(locale="zh-CN")
            page = await context.new_page()
            def track(response: Any) -> None:
                task = asyncio.create_task(observe(response))
                pending.add(task)
                task.add_done_callback(pending.discard)
            page.on("response", track)
            emit("progress", "正在读取抖音公开热榜页面", phase="trends")
            await page.goto(PUBLIC_HOT, wait_until="domcontentloaded", timeout=45000)
            for _ in range(30):
                await pause(1, cancel)
                if topics:
                    break
            if pending:
                await asyncio.gather(*list(pending), return_exceptions=True)
            if not topics:
                detail = failures[-1] if failures else "公开页面未返回热榜数据，可能需要验证或平台页面已改变"
                raise CollectorError("NO_TRENDS", detail)
        finally:
            await browser.close()
    result = {"topics": topics, "capturedAt": utc_now(), "source": PUBLIC_HOT}
    atomic_json(output, result)
    emit("complete", f"取得 {len(topics)} 条公开热榜", count=len(topics), output=str(output))
    return result


def parser() -> argparse.ArgumentParser:
    result = argparse.ArgumentParser(description=__doc__)
    subs = result.add_subparsers(dest="command", required=True)
    sync = subs.add_parser("sync", help="独立临时浏览器扫码并同步自己的作品")
    sync.add_argument("--session-dir", required=True)
    sync.add_argument("--output", required=True)
    sync.add_argument("--view", required=True)
    sync.add_argument("--confirm", help='写入 {"confirmed":true} 才继续；默认为 session-dir/confirm.json')
    sync.add_argument("--cancel", help="创建此文件即取消，默认为 session-dir/cancel")
    sync.add_argument("--limit", type=int, default=10, choices=range(1, 101), metavar="1..100")
    sync.add_argument("--login-timeout", type=int, default=300)
    sync.add_argument("--confirm-timeout", type=int, default=120)
    sync.add_argument("--max-pages", type=int, default=12)
    sync.add_argument("--visible", action="store_true", help="为本人处理正常平台验证显示独立浏览器")
    trends = subs.add_parser("trends", help="通过独立无登录浏览器读取公开热榜")
    trends.add_argument("--output", required=True)
    trends.add_argument("--cancel")
    trends.add_argument("--limit", type=int, default=20, choices=range(1, 51), metavar="1..50")
    return result


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    args = parser().parse_args()
    try:
        asyncio.run(run_sync(args) if args.command == "sync" else run_trends(args))
        return 0
    except CollectorError as exc:
        emit("error", str(exc), code=exc.code)
        return 2
    except KeyboardInterrupt:
        emit("error", "任务已中止", code="CANCELLED")
        return 130
    except Exception as exc:
        # Browser exceptions can contain request URLs. Do not log raw exception
        # text, page HTML, cookies, headers, or query strings into the app.
        emit("error", f"浏览器任务失败（{type(exc).__name__}）；请检查网络、浏览器安装或正常平台验证", code="BROWSER_ERROR")
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
